  static List<ToolSnippet> _familySnippets(String label, String? key) {
    final family = langFamilyOf(key: key, label: label);
    switch (family) {
      case LangFamily.c:
        return cFamily;
      case LangFamily.hash:
        return hashFamily;
      case LangFamily.sql:
        return sqlFamily;
      case LangFamily.xml:
        return xml;
      case LangFamily.lisp:
        return lispFamily;
      case LangFamily.percent:
        return percentFamily;
      case LangFamily.vb:
        return vbFamily;
      case LangFamily.batch:
        return batchFamily;
      case LangFamily.fortran:
        return fortranFamily;
      case LangFamily.none:
        return editor;
    }
  }

  /// 按文本编辑页的语言选出对应的常用符号集。
  ///
  /// [langLabel] 是展示名，[key] 是 re_highlight 的小写标识（更准确）。
  /// 顺序：语言专属 -> 语言族通用 -> 通用编辑符号。
  static List<ToolSnippet> forLanguage(String langLabel, [String key = '']) {
    final exact = _byKey[key];
    if (exact != null) return exact;

    switch (langLabel) {
      case 'HTTP':
        return http;
      case 'JSON':
        return json;
      case 'XML / HTML':
        return xml;
      case 'JavaScript':
        return javascript;
      case 'TypeScript':
        return typescript;
      case 'CSS':
        return css;
      case 'SQL':
        return sql;
      case 'YAML':
        return yaml;
      case 'Markdown':
        return markdown;
      case 'Bash':
        return bash;
      case 'Python':
        return python;
      case 'Java':
        return java;
      case 'Go':
        return go;
      case 'Dart':
        return dart;
      case 'Plain Text':
        return editor;
    }
    return _familySnippets(langLabel, key.isEmpty ? null : key);
  }
